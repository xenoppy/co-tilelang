"""Triton fp16 / fp8 matmul baselines for the claims reproduction (sub-study A, claim C1).

Two kernels, both copied from their sources (only the accumulator lines differ):

* ``tut03``  - the official Triton tutorial 03 kernel at tag v3.4.0 (the installed triton),
  python/tutorials/03-matrix-multiplication.py (md5 of the file 02cbe61de948ed3e5b9997855defe130):
  fp32 accumulator, output cast to fp16, the tutorial's 16 CUDA autotune configs.
* ``tlbench_fp16acc`` - the Triton kernel tilelang-benchmark used for the RTX 4090 / H100 bars
  of images/op_benchmark_consistent_gemm_fp16.png
  (tile-ai/tilelang-benchmark@b658f7e, {ada,hopper}_benchmark/dense_matmul/1.triton-benchmark/
  benchmark_triton_matmul_float16.py): the same kernel and configs, but the accumulator is fp16
  (``tl.zeros(..., tl.float16)`` and ``tl.dot(..., out_dtype=tl.float16)``).

The operand layout is given by the strides of ``b`` (shape (K, N)): pass ``B.T`` of a row-major
(N, K) weight for the NT layout TileLang's benchmark kernels use, or a row-major (K, N) tensor
for the NN layout of the upstream Triton script. Triton's autotune key is (M, N, K) only, so
every (kernel, layout) pair gets its own ``Autotuner`` instance (``make_matmul``) - otherwise
a config tuned for one layout would be silently reused for the other.
"""
